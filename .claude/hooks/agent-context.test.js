'use strict';
// node .claude/hooks/agent-context.test.js: the context hook against made-up agent transcripts.
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert');
const { execFileSync } = require('node:child_process');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ctxhook-')), HOOK = path.join(__dirname, 'agent-context.js');
fs.mkdirSync(path.join(dir, 'sess', 'subagents'), { recursive: true });
let n = 0;
const agent = (type = 'l2-planner') => { const id = 'a' + (++n); fs.writeFileSync(path.join(dir, 'sess', 'subagents', `agent-${id}.meta.json`), JSON.stringify({ agentType: type })); return id; };
const at = (id, ctx) => fs.writeFileSync(path.join(dir, 'sess', 'subagents', `agent-${id}.jsonl`), JSON.stringify({ type: 'assistant', message: { usage: { input_tokens: 10, cache_read_input_tokens: ctx - 10 } } }) + '\n');
const call = (id, tool_name, tool_input = {}) => {
    const out = execFileSync(process.execPath, [HOOK], { input: JSON.stringify({ agent_id: id, transcript_path: path.join(dir, 'sess.jsonl'), tool_name, tool_input }), encoding: 'utf8', env: { ...process.env, L2SOLO_AGENT_CONTEXT_DIR: dir, L2SOLO_AGENT_CONTEXT: '' } });
    return out ? JSON.parse(out).hookSpecificOutput.permissionDecisionReason : '';
};
const bash = (id, command, bg) => call(id, 'Bash', { command, run_in_background: bg });
let id = agent();
at(id, 99000); assert.equal(bash(id, 'grep x'), '', 'under 100k nothing is said');
at(id, 101000); assert.match(bash(id, 'grep x'), /on no file\. This call was refused once/, 'at 100k with nothing written the agent is told to write');
assert.equal(bash(id, 'grep x'), '', 'told once');
at(id, 130000); assert.equal(bash(id, 'grep x'), '', 'not again before 60k more');
at(id, 162000); assert.match(bash(id, 'grep x'), /about 122k of your work is on no file/, 'an agent that wrote nothing is told again 60k later');
id = agent();
at(id, 90000); assert.equal(call(id, 'Write', { file_path: '/x/plan.md' }), '', 'a write passes');
at(id, 140000); assert.equal(bash(id, 'grep x'), '', '50k after a write: silent');
at(id, 151000); assert.match(bash(id, 'grep x'), /about 61k of your work/, '60k after the last write: told');
at(id, 155000); assert.equal(bash(id, 'git -C /w commit -m step'), '', 'a commit counts as a record');
at(id, 171000); assert.match(bash(id, 'node run.js', true), /no room left to wait/, 'past 170k no background command');
assert.equal(bash(id, 'node run.js'), '', 'the same command in the foreground passes');
at(id, 201000); assert.match(bash(id, 'grep x'), /fits in about 15 calls, finish the task .*exact file:line ranges/, 'at 200k: finish or hand over');
assert.equal(bash(id, 'grep x'), '', 'told once, the agent may finish');
at(id, 251000); assert.match(bash(id, 'grep x'), /^Context 251k tokens: only Write, Edit/, 'from 250k only the return work');
assert.equal(call(id, 'Write', { file_path: '/x/handover.md' }), '', 'the hand-over can still be written');
assert.equal(call(id, 'Edit', { file_path: '/x/code.js' }), '', 'an edit passes past the stop');
id = agent('fork'); at(id, 300000); assert.equal(bash(id, 'grep x'), '', 'a fork is not limited');
id = agent(); at(id, 300000); fs.writeFileSync(path.join(dir, `l2solo-agent-context-${id}`), '202345');
assert.match(bash(id, 'grep x'), /only Write, Edit/, 'a mark of the first version still stops at the hard limit');
id = agent(); at(id, 205000); fs.writeFileSync(path.join(dir, `l2solo-agent-context-${id}`), '202345');
assert.equal(bash(id, 'grep x'), '', 'an agent the first version already told is not told again');
assert.equal(execFileSync(process.execPath, [HOOK], { input: JSON.stringify({ transcript_path: path.join(dir, 'sess.jsonl'), tool_name: 'Bash', tool_input: {} }), encoding: 'utf8' }), '', 'the main session is not touched');
fs.rmSync(dir, { recursive: true, force: true });
console.log('agent-context: all PASS');
